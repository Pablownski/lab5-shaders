/// Ancho en píxeles de una línea de texto con la escala dada.
pub fn text_width(text: &str, scale: usize) -> usize {
    text.chars().count() * 6 * scale
}

/// Dibuja `text` en el buffer 0RGB; cada píxel de la fuente se amplía `scale` veces.
pub fn draw_text(buf: &mut [u32], width: usize, x: usize, y: usize, text: &str, scale: usize, color: u32) {
    let height = buf.len() / width;
    for (i, ch) in text.chars().enumerate() {
        for (row, bits) in glyph(ch).iter().enumerate() {
            for col in 0..5 {
                if bits >> (4 - col) & 1 == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let (px, py) = (x + (i * 6 + col) * scale + dx, y + row * scale + dy);
                        if px < width && py < height {
                            buf[py * width + px] = color;
                        }
                    }
                }
            }
        }
    }
}

/// Oscurece un rectángulo para que el texto se lea sobre cualquier fondo.
pub fn dim_rect(buf: &mut [u32], width: usize, x: usize, y: usize, w: usize, h: usize) {
    let height = buf.len() / width;
    for py in y..(y + h).min(height) {
        for px in x..(x + w).min(width) {
            let c = buf[py * width + px];
            let half = |v: u32| v / 3;
            buf[py * width + px] = (half(c >> 16 & 255) << 16) | (half(c >> 8 & 255) << 8) | half(c & 255);
        }
    }
}
